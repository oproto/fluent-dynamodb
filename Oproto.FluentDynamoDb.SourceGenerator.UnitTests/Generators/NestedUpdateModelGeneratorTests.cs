using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Oproto.FluentDynamoDb.SourceGenerator;
using Oproto.FluentDynamoDb.SourceGenerator.UnitTests.TestHelpers;
using Oproto.FluentDynamoDb.SourceGenerator.UnitTests.Integration;

namespace Oproto.FluentDynamoDb.SourceGenerator.UnitTests.Generators;

/// <summary>
/// Unit tests for nested UpdateModel generation for properties with [DynamoDbMap] attribute
/// where the property type has [DynamoDbEntity] attribute.
/// </summary>
[Trait("Category", "Unit")]
[Trait("Generator", "NestedUpdateModel")]
public class NestedUpdateModelGeneratorTests
{
    [Fact]
    public void Generator_WithNestedMapProperty_GeneratesNestedUpdateModelClass()
    {
        // Arrange
        var source = @"
using System;
using Oproto.FluentDynamoDb.Attributes;

namespace TestNamespace
{
    [DynamoDbEntity]
    public partial class Address
    {
        [DynamoDbAttribute(""street"")]
        public string Street { get; set; } = string.Empty;
        
        [DynamoDbAttribute(""city"")]
        public string City { get; set; } = string.Empty;
        
        [DynamoDbAttribute(""zipCode"")]
        public string ZipCode { get; set; } = string.Empty;
    }

    [DynamoDbTable(""customers"")]
    public partial class Customer
    {
        [PartitionKey]
        [DynamoDbAttribute(""pk"")]
        public string Id { get; set; } = string.Empty;
        
        [DynamoDbAttribute(""name"")]
        public string Name { get; set; } = string.Empty;
        
        [DynamoDbMap]
        [DynamoDbAttribute(""address"")]
        public Address ShippingAddress { get; set; } = new();
    }
}";

        // Act
        var result = GenerateCode(source);

        // Assert
        result.Diagnostics.Should().NotContain(d => d.Severity == DiagnosticSeverity.Error);
        
        // Verify nested UpdateModel class is generated by the main generator (for [DynamoDbEntity] types)
        var nestedUpdateModelFile = result.GeneratedSources
            .FirstOrDefault(s => s.FileName.Contains("AddressUpdateModel.g.cs"));
        
        nestedUpdateModelFile.Should().NotBeNull("should generate AddressUpdateModel class");
        
        var code = nestedUpdateModelFile!.SourceText.ToString();
        
        // Verify class structure
        code.ShouldContainClass("AddressUpdateModel");
        code.Should().Contain("namespace TestNamespace", "should preserve entity namespace");
        
        // Verify properties with nullable types
        code.Should().Contain("string? Street", "should generate nullable string for Street property");
        code.Should().Contain("string? City", "should generate nullable string for City property");
        code.Should().Contain("string? ZipCode", "should generate nullable string for ZipCode property");
        
        // Verify XML documentation
        code.Should().Contain("/// <summary>", "should include XML documentation");
    }

