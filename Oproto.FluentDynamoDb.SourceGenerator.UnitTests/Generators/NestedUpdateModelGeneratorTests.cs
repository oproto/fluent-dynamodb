    [Fact]
    public void Generator_WithMultiLevelNesting_GeneratesAllNestedUpdateModels()
    {
        // Arrange
        var source = @"
using System;
using Oproto.FluentDynamoDb.Attributes;

namespace TestNamespace
{
    [DynamoDbEntity]
    public partial class Country
    {
        [DynamoDbAttribute(""code"")]
        public string Code { get; set; } = string.Empty;
        
        [DynamoDbAttribute(""name"")]
        public string Name { get; set; } = string.Empty;
    }

    [DynamoDbEntity]
    public partial class Address
    {
        [DynamoDbAttribute(""city"")]
        public string City { get; set; } = string.Empty;
        
        [DynamoDbMap]
        [DynamoDbAttribute(""country"")]
        public Country Country { get; set; } = new();
    }

    [DynamoDbTable(""orders"")]
    public partial class Order
    {
        [PartitionKey]
        [DynamoDbAttribute(""pk"")]
        public string Id { get; set; } = string.Empty;
        
        [DynamoDbMap]
        [DynamoDbAttribute(""shippingAddress"")]
        public Address ShippingAddress { get; set; } = new();
    }
}";

        // Act
        var result = GenerateCode(source);

        // Assert
        result.Diagnostics.Should().NotContain(d => d.Severity == DiagnosticSeverity.Error);
        
        // Verify CountryUpdateModel is generated
        var countryUpdateModelFile = result.GeneratedSources
            .FirstOrDefault(s => s.FileName.Contains("CountryUpdateModel.g.cs"));
        
        countryUpdateModelFile.Should().NotBeNull("should generate CountryUpdateModel class");
        
        var countryCode = countryUpdateModelFile!.SourceText.ToString();
        countryCode.Should().Contain("string? Code", "should generate nullable string for Code property");
        countryCode.Should().Contain("string? Name", "should generate nullable string for Name property");
        
        // Verify AddressUpdateModel is generated with nested CountryUpdateModel
        var addressUpdateModelFile = result.GeneratedSources
            .FirstOrDefault(s => s.FileName.Contains("AddressUpdateModel.g.cs"));
        
        addressUpdateModelFile.Should().NotBeNull("should generate AddressUpdateModel class");
        
        var addressCode = addressUpdateModelFile!.SourceText.ToString();
        addressCode.Should().Contain("string? City", "should generate nullable string for City property");
        addressCode.Should().Contain("CountryUpdateModel? Country", 
            "should use CountryUpdateModel type for nested Country property");
        
        // Verify OrderUpdateModel uses AddressUpdateModel
        var orderUpdateModelFile = result.GeneratedSources
            .FirstOrDefault(s => s.FileName.Contains("OrderUpdateModel.g.cs"));
        
        orderUpdateModelFile.Should().NotBeNull("should generate OrderUpdateModel class");
        
        var orderCode = orderUpdateModelFile!.SourceText.ToString();
        orderCode.Should().Contain("AddressUpdateModel? ShippingAddress",
            "should use AddressUpdateModel type for ShippingAddress property");
    }

    [Fact]
    public void Generator_WithDictionaryProperty_DoesNotGenerateNestedUpdateModel()
    {
        // Arrange
        var source = @"
using System;
using System.Collections.Generic;
using Oproto.FluentDynamoDb.Attributes;

namespace TestNamespace
{
    [DynamoDbTable(""items"")]
    public partial class Item
    {
        [PartitionKey]
        [DynamoDbAttribute(""pk"")]
        public string Id { get; set; } = string.Empty;
        
        [DynamoDbMap]
        [DynamoDbAttribute(""metadata"")]
        public Dictionary<string, string> Metadata { get; set; } = new();
    }
}";

        // Act
        var result = GenerateCode(source);

        // Assert
        result.Diagnostics.Should().NotContain(d => d.Severity == DiagnosticSeverity.Error);
        
        // Verify no nested UpdateModel is generated for Dictionary
        var nestedUpdateModelFiles = result.GeneratedSources
            .Where(s => s.FileName.Contains("UpdateModel.g.cs") && 
                       !s.FileName.Contains("ItemUpdateModel.g.cs"));
        
        nestedUpdateModelFiles.Should().BeEmpty(
            "should not generate nested UpdateModel for Dictionary types");
        
        // Verify ItemUpdateModel uses Dictionary type directly
        var itemUpdateModelFile = result.GeneratedSources
            .FirstOrDefault(s => s.FileName.Contains("ItemUpdateModel.g.cs"));
        
        itemUpdateModelFile.Should().NotBeNull();
        var code = itemUpdateModelFile!.SourceText.ToString();
        code.Should().Contain("Dictionary<string, string>? Metadata",
            "should use Dictionary type directly for Dictionary properties");
    }

